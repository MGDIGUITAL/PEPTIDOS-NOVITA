// ─── Subida de imagen ──────────────────────────────────────────────────────
async function uploadImage(imageFile, sku) {
  const filePath = path.join(IMAGES_DIR, imageFile);
  if (!fs.existsSync(filePath)) {
    console.warn(`   ⚠️  Imagen no encontrada: ${filePath}`);
    return null;
  }
  const fileBuffer = fs.readFileSync(filePath);
  const ext = path.extname(imageFile).toLowerCase().replace('.', '');
  const mimeType = (ext === 'jpg' || ext === 'jpeg') ? 'image/jpeg' : `image/${ext}`;
  const storagePath = `products/${sku.toLowerCase()}.${ext}`;

  const { error } = await supabase.storage.from(BUCKET).upload(storagePath, fileBuffer, {
    contentType: mimeType,
    upsert: true,
  });
  if (error) {
    console.error(`   ❌ Error subiendo imagen: ${error.message}`);
    return null;
  }
  const { data: { publicUrl } } = supabase.storage.from(BUCKET).getPublicUrl(storagePath);
  console.log(`   📸 Imagen → ${publicUrl}`);
  return publicUrl;
}

// ─── Upsert producto ───────────────────────────────────────────────────────
async function upsertProduct(product, imageUrl) {
  const dbPayload = {
    title:               product.title,
    description:         product.description,
    category:            product.category,
    sale_price:          product.sale_price,
    cost_price:          product.cost_price,
    sku:                 product.sku,
    stock:               product.stock,
    status:              product.status,
    image_url:           imageUrl || null,
    images:              imageUrl ? [imageUrl] : [],
    sizes:               [],
    shipping_profile_id: 'shipping_standard',
  };

  // Intentar update primero por SKU
  const { data: existing } = await supabase
    .from('products')
    .select('id')
    .eq('sku', product.sku)
    .maybeSingle();

  if (existing) {
    const { error } = await supabase.from('products').update(dbPayload).eq('sku', product.sku);
    if (error) {
      console.error(`   ❌ Error actualizando: ${error.message}`);
    } else {
      console.log(`   🔄 Actualizado en DB (id: ${existing.id})`);
    }
  } else {
    const { data, error } = await supabase.from('products').insert(dbPayload).select('id').single();
    if (error) {
      console.error(`   ❌ Error insertando: ${error.message}`);
    } else {
      console.log(`   ✅ Insertado en DB (id: ${data.id})`);
    }
  }
}

// ─── Main ──────────────────────────────────────────────────────────────────
async function main() {
  console.log('\n🚀 NOVA Performance® — Setup DB + Seed de productos\n');
  console.log(`🔗 Supabase: ${SUPABASE_URL}`);

  // 1. Crear tabla vía RPC si no existe
  console.log('\n📋 Creando tabla products si no existe...');
  const { error: sqlError } = await supabase.rpc('exec_sql', { sql: CREATE_TABLE_SQL });
  if (sqlError) {
    // Si no hay función exec_sql, intentar inserción directa (la tabla puede ya existir)
    console.warn(`   ⚠️  RPC exec_sql no disponible: ${sqlError.message}`);
    console.log('   → Intentando inserción directa (tabla puede existir con otro schema)...');
  } else {
    console.log('   ✅ Tabla creada/verificada.');
  }

  // 2. Seed de productos
  console.log('\n📦 Cargando productos...\n');
  let success = 0;

  for (const product of PRODUCTS) {
    console.log(`─── [${product.sku}] ${product.title}`);
    try {
      const imageUrl = await uploadImage(product.image_file, product.sku);
      await upsertProduct(product, imageUrl);
      success++;
    } catch (err) {
      console.error(`   ❌ Error inesperado: ${err.message}`);
    }
  }

  console.log(`\n${'─'.repeat(60)}`);
  console.log(`🎉 Completado: ${success}/${PRODUCTS.length} productos procesados`);
  console.log(`${'─'.repeat(60)}\n`);
}

main().catch(err => {
  console.error('❌ Error fatal:', err.message);
  process.exit(1);
});
