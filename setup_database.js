/**
 * setup_database.js — Inicializa la tabla products con el schema completo
 * y luego re-ejecuta el seed de productos.
 * Ejecutar con: node setup_database.js
 */
require('dotenv').config();
const { createClient } = require('@supabase/supabase-js');
const fs = require('fs');
const path = require('path');

const SUPABASE_URL = process.env.NEXT_PUBLIC_SUPABASE_URL;
const SERVICE_ROLE_KEY = process.env.SUPABASE_SERVICE_ROLE_KEY;
const IMAGES_DIR = path.join(__dirname, 'PRODUCTOS', 'PRODUCTOS');
const BUCKET = 'product-images';

if (!SUPABASE_URL || !SERVICE_ROLE_KEY) {
  console.error('❌ Faltan variables de entorno: NEXT_PUBLIC_SUPABASE_URL o SUPABASE_SERVICE_ROLE_KEY');
  process.exit(1);
}

const supabase = createClient(SUPABASE_URL, SERVICE_ROLE_KEY, {
  auth: { persistSession: false, autoRefreshToken: false },
});

// ─── Crear tabla products via RPC (raw SQL) ──────────────────────────────
const CREATE_TABLE_SQL = `
CREATE TABLE IF NOT EXISTS public.products (
  id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at          TIMESTAMPTZ DEFAULT NOW(),
  title               TEXT NOT NULL,
  description         TEXT,
  sale_price          INTEGER NOT NULL,
  cost_price          INTEGER DEFAULT 0,
  stock               INTEGER,
  category            TEXT NOT NULL,
  image_url           TEXT,
  images              TEXT[] DEFAULT '{}',
  sizes               TEXT[] DEFAULT '{}',
  status              TEXT NOT NULL DEFAULT 'active',
  sku                 TEXT,
  shipping_profile_id TEXT DEFAULT 'shipping_standard',
  weight              NUMERIC,
  dimensions          TEXT,
  reference_image_url TEXT,
  active              BOOLEAN GENERATED ALWAYS AS (status = 'active') STORED
);

-- Índice para búsqueda por SKU
CREATE UNIQUE INDEX IF NOT EXISTS products_sku_idx ON public.products (sku) WHERE sku IS NOT NULL;

-- Reload schema cache
NOTIFY pgrst, 'reload schema';
`;

